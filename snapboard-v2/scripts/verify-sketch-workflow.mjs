import assert from 'node:assert/strict'
import { createServer } from 'vite'
const server = await createServer({ appType:'custom',logLevel:'error',server:{middlewareMode:true,hmr:false},
  plugins:[{name:'command-history-solver-isolation',enforce:'pre',resolveId(source,importer){if(source==='../engine/solveState'&&importer?.endsWith('/src/store/useAppStore.ts'))return '\0history-solve-state'},load(id){if(id==='\0history-solve-state')return 'export async function computeContourState(){return "under"}'} }] })
try {
  const { useAppStore, prepareSplitGeometry } = await server.ssrLoadModule('/src/store/useAppStore.ts')
  const { CreateContourCommand, UpdateContourPointsCommand } = await server.ssrLoadModule('/src/commands/SketchCommands.ts')
  const { dimensionEditCommand } = await server.ssrLoadModule('/src/commands/DimensionEditCommand.ts')
  const { serializeSketchClipboard, parseSketchClipboard, pastedSketchContours } = await server.ssrLoadModule('/src/utils/sketchClipboard.ts')
  const { pasteSketchText } = await server.ssrLoadModule('/src/commands/SketchClipboard.ts')
  const { contourSelectionBounds, contourInsideMarquee } = await server.ssrLoadModule('/src/utils/selectionTransform.ts')
  const { serializeProjectFile, parseProjectFile, projectWorkspaceFromState } = await server.ssrLoadModule('/src/utils/projectFile.ts')
  const arc = {id:'arc-shape',type:'outer',name:'半圆板',closed:true,points:[{x:100,y:10},{x:100,y:90}],arcs:[{id:'arc1',p1:0,p2:1,center:{x:100,y:50},radius:40,sweep:'ccw'}],constraints:[]}
  const rect = {id:'rectangle',type:'outer',name:'矩形',closed:true,originAnchorIdx:0,points:[{x:0,y:0},{x:80,y:0},{x:80,y:60},{x:0,y:60}],constraints:[{id:'width',type:'length',edgeIndex:0,value:40,label:'宽40',labelPos:{x:40,y:-15},driving:true}]}
  const circle = {id:'circle',type:'inner',name:'内孔',closed:true,shape:'circle',center:{x:40,y:30},radius:10,points:[],constraints:[]}
  rect.constraints.push({id:'linked',type:'distance',vertexIdx1:0,vertexIdx2:-2,contourId2:'circle',value:25,label:'中心距25',labelPos:{x:20,y:10},driving:true})
  rect.constraints.push({id:'external',type:'distance',vertexIdx1:0,vertexIdx2:0,contourId2:'outside',value:10,label:'外部距离',labelPos:{x:0,y:0},driving:true})
  const text = serializeSketchClipboard([rect,circle,arc],.5), parsed = parseSketchClipboard(text)
  const copies = pastedSketchContours(parsed,1,{x:10,y:10})
  assert.equal(copies[0].points[1].x,50)
  assert.equal(copies[1].radius,5)
  assert.deepEqual(copies[1].center,{x:30,y:25})
  assert.equal(copies[0].constraints.find(c=>c.type==='length').value,40)
  assert.equal(copies[0].constraints.find(c=>c.id!==copies[0].constraints[0].id).contourId2,copies[1].id)
  assert.equal(copies[0].constraints.length,2)
  assert.equal(copies[0].originAnchorIdx,undefined)
  assert.notEqual(copies[2].arcs[0].id,'arc1')
  copies[2].arcs[0].center.x=500; assert.equal(arc.arcs[0].center.x,100)
  assert.equal(parseSketchClipboard('ordinary text'),null)
  assert.throws(()=>parseSketchClipboard('SNAPBOARD_SKETCH_V1\n'+JSON.stringify({pixelToMM:0,contours:[rect]})))
  const bounds=contourSelectionBounds(arc)
  assert.ok(Math.abs(bounds.maxX-140)<1e-8)
  assert.equal(contourInsideMarquee(arc,{x:95,y:0},{x:105,y:100}),false)
  assert.equal(contourInsideMarquee(arc,{x:95,y:0},{x:145,y:100}),true)
  assert.equal(prepareSplitGeometry([arc],1).targets.length,1,'两端点半圆闭合板必须进入原制造入口')
  useAppStore.getState().newProject('绘图回归')
  const base=structuredClone(useAppStore.getState().project)
  base.parts[0].features=[{id:'sketch1',type:'sketch',name:'旧草图',plane:'xy',contours:[]}]
  base.parts.push({id:'part2',name:'第二零件',material:{name:'PETG',thickness:5},features:[{id:'sketch2',type:'sketch',name:'第二草图',plane:'xy',contours:[]}]})
  useAppStore.setState({project:base})
  useAppStore.getState().setUI({activeSketchId:'sketch2'})
  useAppStore.getState().execute(new CreateContourCommand(rect))
  const target=()=>useAppStore.getState().project.parts[1].features[0]
  assert.equal(target().contours.length,1,'绘图必须进入第二零件中的当前草图')
  useAppStore.getState().setUI({activeSketchId:'sketch1'})
  useAppStore.getState().undo(); assert.equal(target().contours.length,0)
  useAppStore.getState().redo(); assert.equal(target().contours.length,1,'重做不能跟随切换后的草图')
  useAppStore.getState().setUI({activeSketchId:null,selectedContourId:'rectangle',selectedContourIds:['rectangle']})
  const featureCount=()=>useAppStore.getState().project.parts.flatMap(p=>p.features).length
  const n=featureCount()
  useAppStore.getState().execute(new CreateContourCommand(circle))
  assert.equal(featureCount(),n,'重新打开工程后不能创建冲突草图ID或额外空草图')
  useAppStore.getState().setUI({activeSketchId:'sketch2'})
  assert.equal(pasteSketchText(text),3)
  assert.equal(target().contours.length,4)
  const pastedIds=target().contours.slice(1).map(c=>c.id)
  useAppStore.getState().undo(); assert.equal(target().contours.length,1)
  assert.equal(useAppStore.getState().ui.selectedContourId,'rectangle','撤销粘贴应恢复原选择，不能留下悬空副本ID')
  useAppStore.getState().redo(); assert.deepEqual(target().contours.slice(1).map(c=>c.id),pastedIds)
  const c=target().contours[0], old=structuredClone(c)
  const points=c.points.map(p=>({...p,x:p.x===80?120:p.x}))
  useAppStore.getState().execute(dimensionEditCommand(c,points,{}, {...c.constraints[0],value:60,label:'宽60'},'width'))
  assert.equal(target().contours[0].points[1].x,120)
  assert.equal(target().contours[0].constraints[0].value,60)
  useAppStore.getState().undo(); assert.deepEqual(target().contours[0],old,'一次撤销必须同时恢复几何和尺寸')
  useAppStore.getState().redo(); assert.equal(target().contours[0].constraints[0].value,60)
  const hole=useAppStore.getState().project.parts[0].features[0].contours.find(c=>c.id==='circle')
  const owner=target().contours[0], linked=owner.constraints.find(c=>c.id==='linked')
  const crossBefore=JSON.parse(JSON.stringify(useAppStore.getState().project))
  useAppStore.getState().execute(dimensionEditCommand(owner,hole.points,{center:{x:56,y:42}}, {...linked,value:35,label:'中心距35'},'linked',hole))
  assert.deepEqual(hole.center,{x:56,y:42})
  assert.equal(owner.constraints.find(c=>c.id==='linked').value,35)
  useAppStore.getState().undo()
  assert.deepEqual(JSON.parse(JSON.stringify(useAppStore.getState().project)),crossBefore,'跨轮廓孔定位的一次撤销必须同时恢复孔与标注')
  useAppStore.getState().execute(new CreateContourCommand(arc))
  const patch={arcs:[{...arc.arcs[0],center:{x:110,y:50}}]}
  const cmd=new UpdateContourPointsCommand('arc-shape',arc.points,arc.points,patch)
  useAppStore.getState().execute(cmd)
  patch.arcs[0].center.x=999
  useAppStore.getState().undo(); useAppStore.getState().redo()
  assert.equal(target().contours.find(c=>c.id==='arc-shape').arcs[0].center.x,110,'圆心补丁必须独立于拖动预览对象')
  const workspace=projectWorkspaceFromState(useAppStore.getState())
  const restored=parseProjectFile(serializeProjectFile(workspace)).workspace
  assert.deepEqual(restored.project,JSON.parse(JSON.stringify(workspace.project)))
  console.log('PASS: multi-part sketch routing, persistent IDs, clipboard scale/circle/arc/links, atomic paste and dimension/cross-contour undo, arc bounds/manufacturing, deep patches, project roundtrip')
} finally { await server.close() }
