import assert from 'node:assert/strict'
import { createServer } from 'vite'
const server = await createServer({ appType: 'custom', logLevel: 'error', server: { middlewareMode: true, hmr: false } })
const dxf = (entities, unit = 4) => ['0','SECTION','2','HEADER','9','$INSUNITS','70',String(unit),'0','ENDSEC','0','SECTION','2','ENTITIES',...entities.flat(Infinity).map(String),'0','ENDSEC','0','EOF'].join('\n')
const line = (x,y,a,b,layer='plate') => [0,'LINE',8,layer,10,x,20,y,11,a,21,b]
const circle = (x,y,r) => [0,'CIRCLE',8,'holes',10,x,20,y,40,r]
const rectangle = [line(0,0,100,0),line(100,50,0,50),line(0,50,0,0),line(100,0,100,50)]
try {
  const {parseCadDxf, cadContours, dxfUnitScale} = await server.ssrLoadModule('/src/features/cad/dxf.ts')
  const {captureCadGeometry, preserveCadGeometry} = await server.ssrLoadModule('/src/features/cad/lock.ts')
  const {sanitizeContour} = await server.ssrLoadModule('/src/utils/projectFile.ts')
  const drawing = parseCadDxf(dxf([...rectangle,circle(30,25,5),line(200,0,210,0)]))
  assert.equal(drawing.paths.length,3)
  assert.equal(drawing.paths.filter(p=>p.role==='inner').length,1)
  assert.equal(drawing.paths.filter(p=>p.role==='outer').length,1)
  assert.equal(drawing.paths.filter(p=>p.role==='construction').length,1)
  const contours = cadContours(drawing,1,.5,'example.dxf')
  const c = contours.find(c=>c.shape==='circle')
  assert.deepEqual(c.center,{x:60,y:-50}); assert.equal(c.radius,10)
  assert.equal(c.geometryLocked,true); assert.equal(c.source.kind,'dxf')
  assert.equal(sanitizeContour(JSON.parse(JSON.stringify(c))).geometryLocked,true)
  assert.equal(dxfUnitScale(parseCadDxf(dxf(rectangle,0)).unit),undefined)
  assert.equal(dxfUnitScale(1),25.4)
  assert.throws(()=>cadContours(drawing,0,.5,'x'))
  const arc = parseCadDxf(dxf([[0,'ARC',10,0,20,0,40,10,50,0,51,180],line(-10,0,10,0,'0')])).paths[0]
  assert.equal(arc.valid,true); assert.equal(arc.contour.arcs.length,1)
  assert.ok(arc.preview.some(p=>p.y < -9.9))
  const bulge = parseCadDxf(dxf([[0,'LWPOLYLINE',90,2,70,1,10,0,20,0,42,1,10,20,20,0,42,1]])).paths[0]
  assert.equal(bulge.valid,true); assert.equal(bulge.contour.arcs.length,2)
  assert.equal(bulge.contour.arcs[0].radius,10)
  const bow = parseCadDxf(dxf([[0,'LWPOLYLINE',90,4,70,1,10,0,20,0,10,10,20,10,10,0,20,10,10,10,20,0]])).paths[0]
  assert.equal(bow.valid,false)
  const gap = parseCadDxf(dxf([line(0,0,100,0),line(100,0,100,50),line(100,50,0,50),line(0,50,0,.01)]))
  assert.ok(gap.paths.every(p=>!p.valid))
  const duplicateEdge = parseCadDxf(dxf([...rectangle,line(100,50,100,0)]))
  assert.equal(duplicateEdge.paths.length,1)
  assert.equal(duplicateEdge.paths[0].role,'outer')
  assert.ok(duplicateEdge.warnings.includes('Duplicate line entities excluded'))
  assert.throws(()=>parseCadDxf(dxf([[0,'CIRCLE',10,0,20,0,30,1,40,5]])),/XY/)
  assert.throws(()=>parseCadDxf('AutoCAD Binary DXF\0'),/Binary/)
  assert.throws(()=>parseCadDxf('0\nSECTION'),/EOF/)
  const withNotes = parseCadDxf(dxf([...rectangle,[0,'DIMENSION'],[0,'INSERT',2,'block']]))
  assert.equal(withNotes.warnings.length,2)
  const project = {parts:[{features:[{type:'sketch',contours}]}]}
  const snapshot = captureCadGeometry(project)
  c.points[0].x = 999; c.radius = 999; c.type='outer'; c.constraints.push({value:1})
  preserveCadGeometry(project,snapshot)
  assert.equal(c.radius,10); assert.equal(c.type,'outer'); assert.equal(c.constraints.length,0)
  const {ImportCadCommand} = await server.ssrLoadModule('/src/features/cad/ImportCadCommand.ts')
  const {useAppStore} = await server.ssrLoadModule('/src/store/useAppStore.ts')
  const {UpdateContourPointsCommand} = await server.ssrLoadModule('/src/commands/SketchCommands.ts')
  useAppStore.getState().newProject('CAD regression')
  const before = JSON.stringify(useAppStore.getState().project.parts)
  useAppStore.getState().execute(new ImportCadCommand(contours))
  const current = () => useAppStore.getState().project.parts.flatMap(p=>p.features).flatMap(f=>f.type==='sketch'?f.contours:[])
  assert.equal(current().length,3)
  useAppStore.getState().undo()
  assert.equal(JSON.stringify(useAppStore.getState().project.parts),before)
  useAppStore.getState().redo()
  assert.equal(current().length,3)
  const original = structuredClone(current()[0])
  useAppStore.getState().execute(new UpdateContourPointsCommand(original.id,original.points,[{x:999,y:999}],{type:'inner',radius:999}))
  assert.deepEqual(current()[0].points,original.points)
  assert.equal(current()[0].radius,original.radius)
  assert.equal(current()[0].type,'inner')
  useAppStore.getState().undo()
  assert.equal(current()[0].type,original.type)
  console.log('CAD import passed: dimensions, units, topology, arcs, bulges, gaps, exclusions, persistence and geometry lock')
} finally { await server.close() }
