export const SNAPBOARD_ATTRIBUTION_SCHEMA = 'snapboard-attribution/v1' as const
// Code provenance only. This marker is not painted into the UI or user artwork.
export const SNAPBOARD_CODE_WATERMARK = '/*! SnapBoard code origin v1 | https://snapboard.cn/ | https://github.com/Ruoshui1145/snapboard */' as const
export const SNAPBOARD_ATTRIBUTION_TEXT = 'Created with SnapBoard' as const
export const SNAPBOARD_PUBLICATION_NOTICE = 'Made with SnapBoard' as const
export const SNAPBOARD_ORIGIN_URL = 'https://snapboard.cn/' as const
export const SNAPBOARD_SOURCE_NOTICE = '本地来源标识，未签名；编号用于文件对照，不代表官方真伪认证。' as const
export const SNAPBOARD_ATTRIBUTION_REQUIREMENT = 'If you publish an output generated by SnapBoard, keep the notice: Made with SnapBoard.' as const

export interface SnapBoardAttribution {
  schema: typeof SNAPBOARD_ATTRIBUTION_SCHEMA
  generator: 'SnapBoard'
  generatorVersion: string
  attributionText: typeof SNAPBOARD_ATTRIBUTION_TEXT
  publicationNotice: typeof SNAPBOARD_PUBLICATION_NOTICE
  attributionRequired: true
  attributionRequirement: typeof SNAPBOARD_ATTRIBUTION_REQUIREMENT
  projectName: string
  generatedAt: string
  sourceRecordId: string
  originUrl: typeof SNAPBOARD_ORIGIN_URL
  authenticity: 'unsigned-local'
  verificationNotice: typeof SNAPBOARD_SOURCE_NOTICE
}

export interface SnapBoardAttributionInput {
  projectName?: string
  projectVersion?: string
  generatedAt?: string
}

const cleanText = (value: string | undefined, fallback: string): string => {
  const trimmed = value?.trim()
  return trimmed || fallback
}

const sourceRecordId = () => {
  const bytes = crypto.getRandomValues(new Uint8Array(16))
  bytes[6] = (bytes[6] & 15) | 64
  bytes[8] = (bytes[8] & 63) | 128
  const hex = Array.from(bytes, value => value.toString(16).padStart(2, '0')).join('')
  return `SB-${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

export function createSnapBoardAttribution(input: SnapBoardAttributionInput = {}): SnapBoardAttribution {
  return {
    schema: SNAPBOARD_ATTRIBUTION_SCHEMA,
    generator: 'SnapBoard',
    generatorVersion: cleanText(input.projectVersion, '0.0.0'),
    attributionText: SNAPBOARD_ATTRIBUTION_TEXT,
    publicationNotice: SNAPBOARD_PUBLICATION_NOTICE,
    attributionRequired: true,
    attributionRequirement: SNAPBOARD_ATTRIBUTION_REQUIREMENT,
    projectName: cleanText(input.projectName, 'SnapBoard project'),
    generatedAt: cleanText(input.generatedAt, new Date().toISOString()),
    sourceRecordId: sourceRecordId(),
    originUrl: SNAPBOARD_ORIGIN_URL,
    authenticity: 'unsigned-local',
    verificationNotice: SNAPBOARD_SOURCE_NOTICE,
  }
}

export function isSnapBoardAttribution(value: unknown): value is SnapBoardAttribution {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false
  const candidate = value as Partial<SnapBoardAttribution>
  return candidate.schema === SNAPBOARD_ATTRIBUTION_SCHEMA &&
    candidate.generator === 'SnapBoard' &&
    typeof candidate.generatorVersion === 'string' &&
    candidate.attributionText === SNAPBOARD_ATTRIBUTION_TEXT &&
    candidate.publicationNotice === SNAPBOARD_PUBLICATION_NOTICE &&
    candidate.attributionRequired === true &&
    candidate.attributionRequirement === SNAPBOARD_ATTRIBUTION_REQUIREMENT &&
    typeof candidate.projectName === 'string' &&
    typeof candidate.generatedAt === 'string' &&
    typeof candidate.sourceRecordId === 'string' && /^SB-[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/.test(candidate.sourceRecordId) &&
    candidate.originUrl === SNAPBOARD_ORIGIN_URL && candidate.authenticity === 'unsigned-local' &&
    candidate.verificationNotice === SNAPBOARD_SOURCE_NOTICE
}

export function normalizeSnapBoardAttribution(
  value: unknown,
  fallback: SnapBoardAttributionInput = {},
): SnapBoardAttribution {
  // Enumerate our fields: an imported JSON must not promote itself to a signed/certified record.
  const source = typeof value === 'object' && value !== null ? value as Partial<SnapBoardAttribution> : {}
  const normalized = createSnapBoardAttribution({
    projectName: typeof source.projectName === 'string' ? source.projectName : fallback.projectName,
    projectVersion: typeof source.generatorVersion === 'string' ? source.generatorVersion : fallback.projectVersion,
    generatedAt: typeof source.generatedAt === 'string' ? source.generatedAt : fallback.generatedAt,
  })
  if (isSnapBoardAttribution(value)) normalized.sourceRecordId = value.sourceRecordId
  return normalized
}

export function serializeSnapBoardAttribution(attribution: SnapBoardAttribution): string {
  return `${JSON.stringify(attribution, null, 2)}\n`
}
