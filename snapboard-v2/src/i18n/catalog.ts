export function translateUiText(locale: AppLocale, source: string): string {
  if (locale === 'zh-CN' || !source.trim()) return source
  const core = source.trim()
  const normalized = core.replace(/\s+/g, ' ')
  const translated = EN[core] ?? EN[normalized] ?? translateDynamic(normalized)
  return translated ? keepWhitespace(source, translated) : source
}

